#!/usr/bin/env bash
# =============================================================================
# FreightFlow end-to-end smoke test through the API gateway (docs/smoke-test.md).
# Every call states the HTTP status it expects; the script stops at the first one
# that differs and prints the response. Every call is made as a persona of the realm
# (ADR 0016) with a real Keycloak token: customers of two organisations, a carrier,
# an operator, an auditor, and anonymous. Needs curl, python3 (or python), docker compose
# (to read Mailpit and replay an event inside the stack) and the secrets generated by
# scripts/generate_secrets.py.
#
#   docker compose up -d --build --wait && ./scripts/smoke_test.sh
# =============================================================================
set -euo pipefail

GATEWAY="${GATEWAY_URL:-http://127.0.0.1:8080}"
RUN_ID="$(date +%s)-$$"
SCRIPTS="$(cd "$(dirname "$0")" && pwd)"
PYTHON=""
for candidate in python3 python; do
  # Windows ships a python3 alias that only opens the Store: check the interpreter really runs.
  if command -v "$candidate" >/dev/null 2>&1 && "$candidate" -c "" >/dev/null 2>&1; then
    PYTHON="$candidate"
    break
  fi
done
if [[ -z "$PYTHON" ]]; then
  echo "smoke_test: python3 is required to read JSON responses and fetch tokens" >&2
  exit 2
fi

STEP=0
BODY=""
HEADERS=""
TOKEN=""
declare -A TOKENS=()
declare -A TOKEN_TIMES=()

# as <persona>|anonymous : the following calls carry that persona's token, fetched once and renewed after four
# minutes, inside the five-minute lifetime (ADR 0016).
as() {
  if [[ "$1" == anonymous ]]; then
    TOKEN=""
    return
  fi
  local now
  now="$(date +%s)"
  if [[ -z "${TOKENS[$1]:-}" || $((now - ${TOKEN_TIMES[$1]})) -gt 240 ]]; then
    TOKENS[$1]="$("$PYTHON" "${SCRIPTS}/keycloak_token.py" "$1")"
    TOKEN_TIMES[$1]="$now"
  fi
  TOKEN="${TOKENS[$1]}"
}

# call <expected status> <method> <path> [json body] [extra header ...]
call() {
  local expected="$1" method="$2" path="$3" data="${4:-}"
  shift 4 || shift $#
  local args=(-sS -X "$method" "${GATEWAY}${path}" -o "$TMP_BODY" -D "$TMP_HEADERS" -w '%{http_code}')
  if [[ -n "$data" ]]; then
    args+=(-H 'Content-Type: application/json' --data "$data")
  fi
  if [[ -n "$TOKEN" ]]; then
    args+=(-H "Authorization: Bearer ${TOKEN}")
  fi
  for header in "$@"; do
    args+=(-H "$header")
  done
  STEP=$((STEP + 1))
  local status
  status="$(curl "${args[@]}")"
  BODY="$(cat "$TMP_BODY")"
  HEADERS="$(cat "$TMP_HEADERS")"
  if [[ "$status" != "$expected" ]]; then
    echo "FAIL step ${STEP}: ${method} ${path} returned ${status}, expected ${expected}" >&2
    echo "$BODY" >&2
    exit 1
  fi
  echo "ok   ${STEP}: ${method} ${path} -> ${status}"
}

# field <json path like .a.b[0].c> : reads from the last response body
field() {
  "$PYTHON" -c '
import decimal, json, re, sys
value = json.loads(sys.argv[1], parse_float=decimal.Decimal)
try:
    for part in re.findall(r"\.([A-Za-z_][A-Za-z0-9_]*)|\[(\d+)\]", sys.argv[2]):
        value = value[part[0]] if part[0] else value[int(part[1])]
except (KeyError, IndexError, TypeError):
    value = None
print("" if value is None else (json.dumps(value, default=str) if isinstance(value, (dict, list)) else value))
' "$BODY" "$1"
}

# expect <json path> <value> : the last response's field must equal value
expect() {
  local actual
  actual="$(field "$1")"
  if [[ "$actual" != "$2" ]]; then
    echo "FAIL step ${STEP}: $1 is '${actual}', expected '$2'" >&2
    echo "$BODY" >&2
    exit 1
  fi
}

# wait_for <path> <json path> <value> : polls GET <path> (every 0.5 s, up to 30 s) as the current persona until the
# field has the value. The payment saga is asynchronous (ADR 0012): a booking is paid by the relay a moment later.
wait_for() {
  local path="$1" json_path="$2" wanted="$3" actual=""
  for _ in $(seq 1 60); do
    BODY="$(curl -sS -H "Authorization: Bearer ${TOKEN}" "${GATEWAY}${path}")"
    actual="$(field "$json_path")"
    if [[ "$actual" == "$wanted" ]]; then
      STEP=$((STEP + 1))
      echo "ok   ${STEP}: GET ${path} -> ${json_path} = ${wanted}"
      return 0
    fi
    sleep 0.5
  done
  echo "FAIL: ${path} ${json_path} stayed '${actual}', expected '${wanted}' within 30 s" >&2
  echo "$BODY" >&2
  exit 1
}

# expect_header <name> <value> : the last response must carry the header with this value
expect_header() {
  if ! grep -qi "^$1: $2"$'\r'"\?$" <<<"$HEADERS"; then
    echo "FAIL step ${STEP}: header $1 is not '$2'" >&2
    echo "$HEADERS" >&2
    exit 1
  fi
}

