# dc : docker compose for this repository's stack, wherever the script is run from
dc() {
  docker compose --project-directory "${SCRIPTS}/.." "$@"
}

# mail_subjects : the subjects of every email Mailpit holds for the recipient, one per line
mail_subjects() {
  dc exec -T mailpit wget -qO- \
    "http://127.0.0.1:8025/api/v1/search?query=to%3A%22${RECIPIENT}%22&limit=50" \
    | "$PYTHON" -c 'import json,sys; [print(m["Subject"]) for m in json.load(sys.stdin)["messages"]]'
}

# wait_for_mail <subject> : polls Mailpit (every 0.5 s, up to 60 s) until an email with this subject arrived
wait_for_mail() {
  for _ in $(seq 1 120); do
    if mail_subjects | grep -qxF "$1"; then
      STEP=$((STEP + 1))
      echo "ok   ${STEP}: email '${1}' to ${RECIPIENT}"
      return 0
    fi
    sleep 0.5
  done
  echo "FAIL: no email '${1}' to ${RECIPIENT} within 60 s; Mailpit has:" >&2
  mail_subjects >&2 || true
  exit 1
}

# consumed <type> <outcome> : notification-service's count of consumed events of this type and outcome
consumed() {
  dc exec -T notification-service wget -qO- http://127.0.0.1:8083/actuator/prometheus \
    | awk -v type="$1" -v outcome="$2" '$1 ~ /^freightflow_events_consumed_total\{/ && index($1, "type=\"" type "\"") && index($1, "outcome=\"" outcome "\"") { sum += $2 } END { printf "%d\n", sum }'
}

