#!/usr/bin/env python3
"""Writes slo.yml: the SLIs as recording rules over every burn-rate window, and the multi-window, multi-burn-rate
alerts of the Google SRE workbook (chapter 5, "Alerting on SLOs"), for each objective in docs/slo.md.

The objectives live here once; run it after changing one, and commit both files (CI checks they match):

    python3 infra/observability/rules/generate_slo_rules.py
"""
from __future__ import annotations

from pathlib import Path

RUNBOOKS = "https://github.com/tsegale/cross-border-logistics-system/blob/main/docs/runbooks"
WINDOWS = ["5m", "30m", "1h", "2h", "6h", "1d", "3d"]

# name, objective, what a bad event is (numerator), all events (denominator), runbook, summary.
BOOKINGS = 'service="logistics-service",uri="/api/v1/shipments",method="POST"'
TRANSFERS = 'service="banking-service",uri="/api/v1/transfers",method="POST"'
SLOS = [
    ("booking_availability", 0.995,
     f'sum(rate(http_server_requests_seconds_count{{{BOOKINGS},outcome="SERVER_ERROR"}}[{{w}}]))',
     f'sum(rate(http_server_requests_seconds_count{{{BOOKINGS}}}[{{w}}]))',
     "slo-booking-availability.md", "Bookings are failing with server errors"),
    ("transfer_availability", 0.995,
     f'sum(rate(http_server_requests_seconds_count{{{TRANSFERS},outcome="SERVER_ERROR"}}[{{w}}]))',
     f'sum(rate(http_server_requests_seconds_count{{{TRANSFERS}}}[{{w}}]))',
     "slo-transfer-availability.md", "Transfers are failing with server errors"),
    ("booking_latency", 0.95,
     f'(sum(rate(http_server_requests_seconds_count{{{BOOKINGS}}}[{{w}}])) - '
     f'sum(rate(http_server_requests_seconds_bucket{{{BOOKINGS},le="0.5"}}[{{w}}])))',
     f'sum(rate(http_server_requests_seconds_count{{{BOOKINGS}}}[{{w}}]))',
     "slo-booking-latency.md", "Bookings are slower than 500 ms too often"),
    ("email_delivery", 0.99,
     '(sum(rate(freightflow_emails_end_to_end_seconds_count[{w}])) - '
     'sum(rate(freightflow_emails_end_to_end_seconds_bucket{le="60.0"}[{w}])))',
     'sum(rate(freightflow_emails_end_to_end_seconds_count[{w}]))',
     "slo-email-delivery.md", "Emails take longer than 60 s from booking to the mail server too often"),
]

# The workbook's pairs: (long window, short window, burn rate, for, severity). A 2% budget spend in 1 h or 5% in 6 h
# pages; 10% in 1 d or 10% in 3 d is a ticket.
ALERTS = [
    ("fast", "page", [("1h", "5m", 14.4), ("6h", "30m", 6)], "2m"),
    ("slow", "ticket", [("1d", "2h", 3), ("3d", "6h", 1)], "15m"),
]


def camel(name: str) -> str:
    return "".join(part.capitalize() for part in name.split("_"))


def render() -> str:
    lines = [
        "# Generated by generate_slo_rules.py from the objectives in docs/slo.md. Do not edit by hand.",
        "groups:",
    ]
    for name, objective, bad, total, _, _ in SLOS:
        lines += [f"  - name: sli-{name.replace('_', '-')}", "    rules:"]
        for w in WINDOWS:
            lines += [
                f"      - record: slo:{name}:error_ratio_rate{w}",
                f"        expr: ({bad.replace('{w}', w)}) / ({total.replace('{w}', w)})",
                f"        labels:",
                f"          slo: {name}",
            ]
    lines += ["  - name: slo-burn-rate-alerts", "    rules:"]
    for name, objective, _, _, runbook, summary in SLOS:
        budget = round(1 - objective, 6)
        for speed, severity, pairs, hold in ALERTS:
            condition = " or ".join(
                f"(slo:{name}:error_ratio_rate{long} > ({rate} * {budget}) and "
                f"slo:{name}:error_ratio_rate{short} > ({rate} * {budget}))"
                for long, short, rate in pairs)
            lines += [
                f"      - alert: {camel(name)}BudgetBurn{speed.capitalize()}",
                f"        expr: {condition}",
                f"        for: {hold}",
                f"        labels:",
                f"          severity: {severity}",
                f"          slo: {name}",
                f"        annotations:",
                f"          summary: \"{summary} ({speed} burn of the {objective * 100:g} % objective)\"",
                f"          description: \"Error ratio {{{{ $value | humanizePercentage }}}} over the long window; at "
                f"this rate the 28-day budget of {budget * 100:g} % runs out early.\"",
                f"          runbook_url: {RUNBOOKS}/{runbook}",
            ]
    return "\n".join(lines) + "\n"


# Per SLO, the series a test feeds in: (metric, labels) for all events and for the bad (or good, for latency) ones.
TEST_SERIES = {
    "booking_availability": ("http_server_requests_seconds_count", BOOKINGS, "bad", ',outcome="SERVER_ERROR"'),
    "transfer_availability": ("http_server_requests_seconds_count", TRANSFERS, "bad", ',outcome="SERVER_ERROR"'),
    "booking_latency": ("http_server_requests_seconds", BOOKINGS, "good", ',le="0.5"'),
    "email_delivery": ("freightflow_emails_end_to_end_seconds", 'service="notification-service"', "good", ',le="60.0"'),
}


def render_tests() -> str:
    """Per SLO: 10 % bad events fire both alerts; a bad ratio inside the budget fires neither."""
    lines = [
        "# Generated by generate_slo_rules.py. promtool test rules (CI, ADR 0033).",
        "rule_files:",
        "  - ../slo.yml",
        "",
        "evaluation_interval: 1m",
        "",
        "tests:",
    ]
    for name, objective, _, _, runbook, summary in SLOS:
        metric, labels, kind, extra = TEST_SERIES[name]
        budget = round(1 - objective, 6)
        # Burning: 20 times the budget's rate, above both fast pairs' thresholds (14.4 and 6), capped at 90 %.
        burning = min(round(100 * budget * 20, 3), 90)
        for case, bad_per_min, fires in [("burning", burning, True), ("inside the budget", round(100 * budget / 2, 3), False)]:
            good_per_min = 100 - bad_per_min
            lines += [f"  - name: {name} {case}", "    interval: 1m", "    input_series:"]
            if kind == "bad":
                lines += [
                    f"      - series: '{metric}{{{labels},outcome=\"SUCCESS\"}}'",
                    f"        values: '0+{good_per_min}x180'",
                    f"      - series: '{metric}{{{labels}{extra}}}'",
                    f"        values: '0+{bad_per_min}x180'",
                ]
            else:
                lines += [
                    f"      - series: '{metric}_count{{{labels}}}'",
                    f"        values: '0+100x180'",
                    f"      - series: '{metric}_bucket{{{labels}{extra}}}'",
                    f"        values: '0+{good_per_min}x180'",
                ]
            lines += ["    alert_rule_test:"]
            for speed, severity, _, _ in ALERTS:
                alert = f"{camel(name)}BudgetBurn{speed.capitalize()}"
                lines += [f"      - eval_time: 120m", f"        alertname: {alert}"]
                if not fires:
                    lines += ["        exp_alerts: []"]
                    continue
                lines += [
                    "        exp_alerts:",
                    f"          - exp_labels: {{severity: {severity}, slo: {name}}}",
                    "            exp_annotations:",
                    f"              summary: \"{summary} ({speed} burn of the {objective * 100:g} % objective)\"",
                    f"              description: \"Error ratio {bad_per_min:g}% over the long window; at this rate the 28-day budget "
                    f"of {budget * 100:g} % runs out early.\"",
                    f"              runbook_url: {RUNBOOKS}/{runbook}",
                ]
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    here = Path(__file__).resolve().parent
    (here / "slo.yml").write_bytes(render().encode())
    (here / "tests" / "slo.test.yml").write_bytes(render_tests().encode())
    print(f"wrote {here / 'slo.yml'} and {here / 'tests' / 'slo.test.yml'}")
